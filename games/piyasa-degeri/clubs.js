export function formatMarketValue(val) {
  if (val >= 1_000_000_000) {
    const b = (val / 1_000_000_000).toFixed(2);
    return `€${b.replace('.00', '')} Milyar`;
  }
  const m = Math.round(val / 1_000_000);
  return `€${m} Milyon`;
}

export function formatFullCurrency(val) {
  return new Intl.NumberFormat('de-DE', {
    style: 'currency',
    currency: 'EUR',
    maximumFractionDigits: 0
  }).format(val);
}

